"""Macros and tables for the datasets of the first submission, re-analysed
under win rate. Source: Poker_trust research_data/checks/b2/*.json (written by
analysis/metric_change.py from the released databases).
  python3 gen_legacy.py REPO PAPER/generated
"""
import json, os, sys
import numpy as np
repo, out = sys.argv[1], sys.argv[2]
B2 = os.path.join(repo, "research_data/checks/b2")
ARCH = ["oracle", "sentinel", "firestorm", "wall", "phantom", "predator", "mirror", "judge"]
DISP = {"oracle": "Balanced", "sentinel": "Tight-aggressive", "firestorm": "Maniac", "wall": "Calling station",
        "phantom": "Bluffer", "predator": "Exploiter", "mirror": "Mimic", "judge": "Grudger"}
SETS = {  # key -> (file, macro stem, label, seeds x hands, temperature, engine)
    "pubfixed": ("a3pre_phase1", "PubFixed", "Fixed rules, engine before the correction", "5 x 10,000", "--", "before"),
    "curfixed": ("a3_phase1", "CurFixed", "Fixed rules, engine after the correction", "5 x 10,000", "--", "after"),
    "pubhill": ("a3pre_phase2_bounded", "PubHill", "Bounded hill-climbing, engine before the correction", "5 x 10,000", "--", "before"),
    "curhill": ("a3_phase2_bounded", "CurHill", "Bounded hill-climbing, engine after the correction", "5 x 10,000", "--", "after"),
    "pubunb": ("a3pre_phase2_unb_aggr", "PubUnb", "Unbounded hill-climbing, engine before the correction", "5 x 10,000", "--", "before"),
    "curunb": ("a3_phase2_unb_aggr", "CurUnb", "Unbounded hill-climbing, engine after the correction", "5 x 10,000", "--", "after"),
    "role": ("phase3", "Role", "Role-play", "5 x 500", "1.0", "before"),
    "noreason": ("no_cot", "NoReason", "Memory and notes, no reasoning step", "5 x 150", "0", "after"),
    "scaf": ("phase31_n20", "Scaf", "Reasoning step, memory and notes", "20 x 150", "0", "after"),
}
def sg(x, d=2): return f"{x:+.{d}f}".replace("-", "$-$").replace("+", "$+$")
def sg1(x): return sg(x, 1)
macros, data = [], {}
def M(name, val): macros.append(f"\\newcommand{{\\num{name}}}{{{val}}}")
for key, (fn, stem, label, nh, temp, eng) in SETS.items():
    d = json.load(open(os.path.join(B2, fn + ".json")))
    s, A = d["summary"], d["archetypes"]
    M(stem + "RStack", sg(s["pearson_stack"]["mean"])); M(stem + "RNet", sg(s["pearson_net"]["mean"]))
    M(stem + "RNetLo", sg(s["pearson_net"]["ci95_t"][0])); M(stem + "RNetHi", sg(s["pearson_net"]["ci95_t"][1]))
    M(stem + "RStackLo", sg(s["pearson_stack"]["ci95_t"][0])); M(stem + "RStackHi", sg(s["pearson_stack"]["ci95_t"][1]))
    M(stem + "RNetPos", s["pearson_net"]["n_positive"]); M(stem + "N", s["pearson_net"]["n"])
    row = {}
    for a in ARCH:
        v = A[a]; sw = np.array(v["seed_win_rates_chips_per_100"]) / 2
        se = float(sw.std(ddof=1) / np.sqrt(len(sw)))
        row[a] = {"wr": v["win_rate_bb_per_100"], "se": se, "showdowns": v["showdowns_per_seed"],
                  "hand_sd": v["per_hand_sd_chips"] / 2}
        tag = stem + {"oracle": "Bal", "sentinel": "Tag", "firestorm": "Man", "wall": "Sta", "phantom": "Blf",
                      "predator": "Exp", "mirror": "Mim", "judge": "Grd"}[a]
        M(tag + "Wr", sg1(row[a]["wr"])); M(tag + "Se", f"{se:.1f}"); M(tag + "Sd", f"{row[a]['showdowns']:.0f}")
    trust = {a: [] for a in ARCH}
    for r in d["per_run"]:
        for a, t in zip(r["archetypes"], r["trust"]): trust[a].append(t)
    for a in ARCH: row[a]["trust"] = float(np.mean(trust[a]))
    data[key] = {"label": label, "nh": nh, "temp": temp, "engine": eng, "summary": s, "rows": row}
open(os.path.join(out, "numbers_legacy.tex"), "w").write("% generated by gen_legacy.py; do not edit\n" + "\n".join(macros) + "\n")
json.dump(data, open(os.path.join(out, "legacy.json"), "w"), indent=1)

# main-text table: the three language-model datasets
lines = []
for key in ("role", "noreason", "scaf"):
    d = data[key]; s = d["summary"]; r = d["rows"]
    best = max(ARCH, key=lambda a: r[a]["wr"])
    lines.append(" & ".join([
        d["label"], d["nh"].replace("x", "$\\times$"), d["temp"],
        sg(s["pearson_stack"]["mean"]),
        f"{sg(s['pearson_net']['mean'])} [{sg(s['pearson_net']['ci95_t'][0])}, {sg(s['pearson_net']['ci95_t'][1])}]",
        f"{sg1(r['wall']['wr'])} ({r['wall']['se']:.0f})", f"{sg1(r['firestorm']['wr'])} ({r['firestorm']['se']:.0f})",
        f"{r['sentinel']['showdowns']:.0f} / {r['wall']['showdowns']:.0f}"]) + r" \\")
open(os.path.join(out, "tab_llm.tex"), "w").write(
    "\\begin{tabular}{lcccccccc}\n\\toprule\n"
    " & Seeds $\\times$ & Temp- & $r$, final & $r$, win rate & Calling station & Maniac & Showdowns per seed, \\\\\n"
    "Prompt condition & hands & erature & stack & [95\\% interval] & bb/100 (SE) & bb/100 (SE) & tight-agg.\\ / station \\\\\n\\midrule\n"
    + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n")

# supplement table: every earlier dataset, win rate per archetype
hdr = " & ".join(["Dataset", "$r$ stack", "$r$ win rate"] + [DISP[a].replace("Tight-aggressive", "TAG").replace("Calling station", "Station") for a in ARCH])
lines = []
for key, d in data.items():
    s = d["summary"]; r = d["rows"]
    lines.append(" & ".join([d["label"] + f" ({d['nh'].replace('x', '$\\times$')})", sg(s["pearson_stack"]["mean"]), sg(s["pearson_net"]["mean"])]
                            + [f"{sg1(r[a]['wr'])} ({r[a]['se']:.1f})" for a in ARCH]) + r" \\")
open(os.path.join(out, "tab_legacy_all.tex"), "w").write(
    "\\begin{tabular}{p{4.6cm}cc" + "c" * 8 + "}\n\\toprule\n" + hdr + " \\\\\n\\midrule\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n")
print(len(macros), "macros;", "tables: tab_llm.tex, tab_legacy_all.tex")
